const SILVER = '#c0c4cc';

// สีที่ผู้เล่น viewer เห็นบนป้ายของ target: เห็นสีจริงเฉพาะอาชีพเดียวกัน (ยกเว้นไพร่เห็นเงินหมด)
function badgeColor(viewerRole, targetRole) {
  if (!viewerRole || !targetRole) return SILVER;
  if (viewerRole !== 'serf' && viewerRole === targetRole) return ROLES[targetRole].color;
  return SILVER;
}

// ---------- การกระจายบทบาทอัตโนมัติตามจำนวนผู้เล่น (6–40 คน) ----------
function roleSetup(n) {
  const c = {
    lord: 1,
    enemy: Math.max(1, Math.min(5, Math.round(n / 8))),
    thief: Math.max(1, Math.min(5, Math.round(n / 8))),
    doctor: n >= 24 ? 2 : 1,
    spy: n >= 24 ? 2 : (n >= 8 ? 1 : 0),
    noble: n >= 24 ? 2 : (n >= 10 ? 1 : 0),
    mad: n >= 10 ? 1 : 0,
    slave: n >= 20 ? 2 : (n >= 12 ? 1 : 0),
  };
  let sum = Object.values(c).reduce((a, b) => a + b, 0);
  // ถ้าเกิน ตัดบทบาทลำดับรอง
  const trim = ['slave', 'mad', 'noble', 'spy', 'doctor'];
  let ti = 0;
  while (sum > n - 1 && ti < trim.length) {
    if (c[trim[ti]] > 0) { c[trim[ti]]--; sum--; } else ti++;
  }
  c.serf = Math.max(0, n - sum);
  return c;
}

// จำนวนที่ศัตรูสังหารได้ต่อคืน
function killQuota(night) {
  if (night <= 3) return 1;
  if (night === 4) return 2;
  if (night === 5) return 3;
  return 4;
}

